#include "vec2.h"

#include <cmath>


//-----------------------------------------------------------------------------
Vec2::Vec2()
   : _x(0.0f),
     _y(0.0f)
{
}


//-----------------------------------------------------------------------------
Vec2::Vec2(float x, float y)
   : _x(x),
     _y(y)
{
}


//-----------------------------------------------------------------------------
float Vec2::x() const
{
   return _x;
}


//-----------------------------------------------------------------------------
float Vec2::y() const
{
   return _y;
}


//-----------------------------------------------------------------------------
void Vec2::setX(float x)
{
   _x = x;
}


//-----------------------------------------------------------------------------
void Vec2::setY(float y)
{
   _y = y;
}


//-----------------------------------------------------------------------------
float Vec2::length() const
{
   return std::sqrt(_x * _x + _y * _y);
}


//-----------------------------------------------------------------------------
Vec2 Vec2::operator-(const Vec2& other) const
{
   return Vec2(_x - other._x, _y - other._y);
}
